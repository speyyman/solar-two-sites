"""Turn results/*.json into LaTeX macros and tables, and one flat summary.

The paper only quotes numbers through these macros, and the website and essay are
checked against results/summary.json by scripts/check_numbers.py, so every number a
reader sees traces back to a file this pipeline wrote.
"""

from __future__ import annotations

import json
import re

import pandas as pd

from pipeline.config import PAPER, PRIMARY_NWP, RESULTS, SITES
from pipeline.evaluate import MAIN, POINT, REF
from pipeline.figures import LABELS

GEN = PAPER / "generated"
ABBR = {"arbuckle": "Arb", "kersey": "Ker"}
CODE = {
    "persistence": "Pers",
    "smart_persistence": "Smart",
    f"physical/{PRIMARY_NWP}": "Phys",
    f"physical_cal/{PRIMARY_NWP}": "PhysCal",
    f"gbm/{PRIMARY_NWP}": "Gbm",
    "physical/ecmwf": "PhysEc",
    "physical_cal/ecmwf": "PhysCalEc",
    "gbm/ecmwf": "GbmEc",
    "physical/era5": "PhysEra",
    "physical_cal/era5": "PhysCalEra",
    "gbm/era5": "GbmEra",
    f"gbm_transfer/{PRIMARY_NWP}": "Transfer",
}


def f3(x: float) -> str:
    return f"{x:.3f}"


def sk(x: float) -> str:
    return f"{x:+.2f}"


def pct(x: float) -> str:
    return f"{100 * x:.0f}"


class Macros:
    def __init__(self) -> None:
        self.items: dict[str, str] = {}

    def add(self, name: str, value: str) -> None:
        assert re.fullmatch(r"[A-Za-z]+", name), name
        assert name not in self.items, name
        self.items[name] = value

    def tex(self) -> str:
        lines = ["% Generated by pipeline/report.py. Do not edit."]
        for k, v in self.items.items():
            lines.append(f"\\newcommand{{\\{k}}}{{{v.replace('%', chr(92) + '%')}}}")
        return "\n".join(lines) + "\n"


def words(n: int) -> str:
    return str(n)


def build_macros(m: dict, fails: dict, led: pd.DataFrame) -> Macros:
    mac = Macros()
    for key, a in ABBR.items():
        site = SITES[key]
        full = m["sites"][key]["full"]
        com = m["sites"][key]["common"]
        mac.add(f"{a}Hours", f"{full['hours']:,}")
        mac.add(f"{a}Days", str(full["days"]))
        mac.add(f"{a}First", full["first_day"])
        mac.add(f"{a}Last", full["last_day"])
        mac.add(f"{a}DcKw", f"{site.dc_kw:,.0f}")
        mac.add(f"{a}AcKw", f"{site.ac_kw:,.1f}".rstrip("0").rstrip("."))
        for c in POINT:
            p = full["point"][c]
            code = CODE[c]
            mac.add(f"{a}{code}Nrmse", f3(p["nrmse"]))
            mac.add(f"{a}{code}Nmae", f3(p["nmae"]))
            mac.add(f"{a}{code}Bias", f"{p['bias']:+.3f}")
            if c != REF:
                lo, hi = full["skill_ci95"][c]
                mac.add(f"{a}{code}Skill", sk(p["skill"]))
                mac.add(f"{a}{code}Lo", sk(lo))
                mac.add(f"{a}{code}Hi", sk(hi))
                mac.add(f"{a}{code}SkillCommon", sk(com["point"][c]["skill"]))
        mac.add(f"{a}SmartNrmseCommon", f3(com["point"][REF]["nrmse"]))
        mac.add(f"{a}DaysCommon", str(com["days"]))
        for src, code in (("gfs", "Gfs"), ("ecmwf", "Ec"), ("era5", "Era")):
            q = full["quantile"][src]
            mac.add(f"{a}Cov{code}", pct(q["coverage_80"]))
            mac.add(f"{a}Width{code}", f3(q["width_80"]))
            mac.add(f"{a}Pinball{code}", f"{q['pinball']:.4f}")
            lo, hi = full["gbm_minus_physical_cal_rmse_ci95"][src]
            mac.add(f"{a}GainLo{code}", f"{lo:+.3f}")
            mac.add(f"{a}GainHi{code}", f"{hi:+.3f}")
        lo, hi = full["gbm_minus_transfer_rmse_ci95"]
        mac.add(f"{a}TransferGapLo", f"{lo:+.3f}")
        mac.add(f"{a}TransferGapHi", f"{hi:+.3f}")
        for sky in ("clear", "mixed", "overcast"):
            b = full["by_sky"][sky]
            s = sky.capitalize()
            mac.add(f"{a}{s}Days", str(b["days"]))
            mac.add(f"{a}{s}GbmNrmse", f3(b["point"][MAIN]["nrmse"]))
            mac.add(f"{a}{s}SmartNrmse", f3(b["point"][REF]["nrmse"]))
            mac.add(f"{a}{s}GbmSkill", sk(b["point"][MAIN]["skill"]))
            mac.add(f"{a}{s}PhysCalSkill", sk(b["point"][f"physical_cal/{PRIMARY_NWP}"]["skill"]))
        fs = fails["sites"][key]
        mac.add(f"{a}WorstTenAbs", pct(fs["share_abs_error_worst_10pct_days"]))
        mac.add(f"{a}WorstTenSq", pct(fs["share_sq_error_worst_10pct_days"]))
        mac.add(f"{a}DaysOverOne", str(fs["days_abs_err_gt_1h"]))
        sens = fs["without_plant_anomaly_days"]
        mac.add(f"{a}AnomalyDays", str(sens["days_removed"]))
        for c, code in (
            (MAIN, "Gbm"),
            (f"physical_cal/{PRIMARY_NWP}", "PhysCal"),
            ("gbm/era5", "GbmEra"),
        ):
            mac.add(f"{a}Sens{code}Skill", sk(sens[c]["skill"]))
            lo, hi = sens[c]["skill_ci95"]
            mac.add(f"{a}Sens{code}Lo", sk(lo))
            mac.add(f"{a}Sens{code}Hi", sk(hi))
        cats = fs["all_days_categories_abs_err_gt_1h"]
        for cat, code in (
            ("no output at all under a sunny sky", "NoOutput"),
            ("one inverter offline", "InvOff"),
            ("reactive-power limit", "Reactive"),
            ("snow likely", "Snow"),
            ("clear dry sky, low output", "ClearDry"),
            ("still winter day, reanalysis clear", "StillWinter"),
            ("forecast missed cloud", "MissCloud"),
            ("cloud neither source saw", "NeitherCloud"),
            ("forecast missed sun", "MissSun"),
            ("sun neither source saw", "NeitherSun"),
            ("over-forecast, no clear cause", "OverNone"),
            ("under-forecast, no clear cause", "UnderNone"),
        ):
            mac.add(f"{a}Cat{code}", str(cats.get(cat, 0)))
        rows = led[(led["site"] == key) & led["stage"].isin(["power", "features"])]

        def count(rule_start: str, rows: pd.DataFrame = rows) -> int:
            r = rows[rows["rule"].str.startswith(rule_start)]
            return int(r["count"].sum())

        mac.add(f"{a}LedStuck", f"{count('identical non-zero'):,}")
        mac.add(f"{a}LedNeg", f"{count('negative power'):,}")
        mac.add(f"{a}LedThin", f"{count('hour with under 75'):,}")
        mac.add(f"{a}LedAmbig", f"{count('timestamp ambiguous'):,}")
        mac.add(f"{a}LedPersistFill", f"{count('persistence: D-1 missing'):,}")
        mac.add(f"{a}LedSmartFill", f"{count('smart persistence: D-1'):,}")
    return mac


def results_table(m: dict) -> str:
    rows = [c for c in LABELS]
    out = [
        "% Generated by pipeline/report.py. Do not edit.",
        r"\begin{tabular}{lrrrrrr}",
        r"\toprule",
        r" & \multicolumn{3}{c}{Arbuckle, CA} & \multicolumn{3}{c}{Kersey, CO} \\",
        r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}",
        r"Forecaster & nMAE & nRMSE & Skill & nMAE & nRMSE & Skill \\",
        r"\midrule",
    ]
    for c in rows:
        cells = [LABELS[c]]
        for key in SITES:
            p = m["sites"][key]["full"]["point"][c]
            cells += [f3(p["nmae"]), f3(p["nrmse"]), "--" if c == REF else sk(p["skill"])]
        out.append(" & ".join(cells) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(out) + "\n"


def ledger_table(led: pd.DataFrame) -> str:
    out = [
        "% Generated by pipeline/report.py. Do not edit.",
        r"\begin{tabular}{llrl}",
        r"\toprule",
        r"Site & Rule & Count & Unit \\",
        r"\midrule",
    ]
    skip = ("raw samples read",)
    for _, r in led.iterrows():
        if r["rule"].startswith(skip) or r["site"] == "discard":
            continue
        rule = str(r["rule"]).replace("%", r"\%").replace("&", r"\&")
        out.append(
            f"{SITES[r['site']].place.split(',')[0]} & {rule} & {r['count']:,} & {r['unit']} \\\\"
        )
    out += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(out) + "\n"


def run() -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    m = json.loads((RESULTS / "metrics.json").read_text())
    fails = json.loads((RESULTS / "failures.json").read_text())
    led = pd.concat(
        [pd.read_csv(RESULTS / "ledger_clean.csv"), pd.read_csv(RESULTS / "ledger_features.csv")],
        ignore_index=True,
    )
    led = led[led["site"].isin(list(SITES))]
    mac = build_macros(m, fails, led)
    (GEN / "numbers.tex").write_text(mac.tex(), newline="\n")
    (GEN / "results_table.tex").write_text(results_table(m), newline="\n")
    (GEN / "ledger_table.tex").write_text(ledger_table(led), newline="\n")
    (RESULTS / "summary.json").write_text(json.dumps(mac.items, indent=2) + "\n", newline="\n")
    print(f"{len(mac.items)} macros written to {GEN / 'numbers.tex'}")
